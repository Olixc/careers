// GitHub Pages serves main as-is (no build step there), so the generated pages are committed.
// `node build.mjs` writes them; `node build.mjs --check` fails if they are out of date.
// Removing a role from jobs.mjs does not delete its folder: delete that by hand.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { jobs } from "./jobs.mjs"

const ROOT = dirname(fileURLToPath(import.meta.url))
const EMAIL = "info@fiilar.com"
const SITE = `https://${readFileSync(join(ROOT, "CNAME"), "utf8").trim()}`
const GENERATED = "<!-- Generated by build.mjs from jobs.mjs. Edit those, then run: node build.mjs -->"

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")
// Noon Lagos time, so the date cannot slip a day whichever timezone runs the build.
const closing = (job) =>
  job.closes && new Date(`${job.closes}T12:00:00+01:00`).toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long", year: "numeric", timeZone: "Africa/Lagos" })
const pad = (html, n) => html.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n")

const mailto = (job, withBody) => {
  // encodeURIComponent, so the "&" in a title cannot cut the subject short.
  const subject = `subject=${encodeURIComponent(`Application: ${job.title} (${job.city})`)}`
  if (!withBody) return `mailto:${EMAIL}?${subject}`
  const fields = job.applyFields ?? ["Name:", "Phone:", `Location in ${job.city}:`, "A bit about me:"]
  const body = `Hi Fiilar team,\n\nI'd like to apply for the ${job.title} role.\n\n${fields.join("\n")}\n`
  return `mailto:${EMAIL}?${subject}&body=${encodeURIComponent(body)}`
}

const chips = (job) =>
  [
    `<div class="chips">`,
    ...(job.pay ? [`  <span class="chip pay money">${esc(job.pay)}</span>`] : []),
    ...job.chips.map((c) => `  <span class="chip">${esc(c)}</span>`),
    ...(job.closes ? [`  <span class="chip">⏳ Open till ${closing(job)}</span>`] : []),
    `</div>`,
  ].join("\n")

const block = (b) => {
  if (b.p) return `<p>${b.p}</p>`
  if (b.h3) return `<h3>${esc(b.h3)}</h3>`
  if (b.list) return [`<ul class="list">`, ...b.list.map((li) => `  <li>${li}</li>`), `</ul>`].join("\n")
  if (b.table)
    return [
      `<div class="table-wrap">`,
      `  <table class="data-table">`,
      `    <thead><tr>${b.table.head.map((h) => `<th>${esc(h)}</th>`).join("")}</tr></thead>`,
      `    <tbody>`,
      ...b.table.rows.map((r) => `      <tr>${r.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`),
      `    </tbody>`,
      `  </table>`,
      `</div>`,
    ].join("\n")
  throw new Error(`Unknown block in jobs.mjs: ${JSON.stringify(b)}`)
}

const section = (s) =>
  [`<section class="block">`, `  <h2>${esc(s.title)}</h2>`, ...s.blocks.map((b) => pad(block(b), 2)), `</section>`].join("\n")

const applyCard = (job) => `<section class="block" id="apply">
  <div class="apply-card">
    <h2>Ready to join the team?</h2>
    <p>${job.applyText}</p>
${job.closes ? `    <p class="closes">Applications close ${closing(job)}.</p>\n` : ""}
    <div class="apply-methods">
      <div class="apply-row">
        <div class="ic">
          <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><rect x="2" y="4" width="20" height="16" rx="2"/><path d="m22 7-10 5L2 7"/></svg>
        </div>
        <div>
          <div class="label">${esc(job.applyLabel ?? "Apply via email")}</div>
          <div class="val"><a href="${esc(mailto(job, false))}">${EMAIL}</a> <button class="copy" type="button" data-copy="${EMAIL}" hidden>Copy</button></div>
        </div>
      </div>
    </div>

    <div class="btns">
      <a class="cta" style="margin-top:0;" href="${esc(mailto(job, true))}">Email your application</a>
    </div>
  </div>
</section>`

const page = ({ base, meta, share, headerCta, main }) => `<!DOCTYPE html>
${GENERATED}
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${esc(meta.title)}</title>
  <link rel="icon" type="image/png" href="${base}logo-icon.png" />
  <meta name="description" content="${esc(meta.description)}" />

  <meta property="og:title" content="${esc(meta.ogTitle)}" />
  <meta property="og:description" content="${esc(meta.ogDescription)}" />
  <meta property="og:type" content="website" />
  <meta property="og:url" content="${share.url}" />
${share.image ? `  <meta property="og:image" content="${share.image}" />
  <meta property="og:image:alt" content="${esc(share.imageAlt)}" />
  <meta name="twitter:card" content="summary" />
` : ""}
  <link rel="stylesheet" href="${base}styles.css" />
</head>
<body>

  <header>
    <div class="wrap header-row">
      <a class="logo" href="${base || "./"}"><img src="${base}logo.svg" alt="Fiilar" /><span>Careers</span></a>
${headerCta ? `      <a class="cta" style="margin:0; padding:10px 20px; font-size:14px;" href="#apply">Apply now</a>\n` : ""}    </div>
  </header>

  <main>
    <div class="wrap">
${pad(main, 6)}
    </div>
  </main>

  <footer>
    <div class="wrap footer-row">
      <div class="logo"><img src="${base}logo.svg" alt="Fiilar" /></div>
      <div>
        <a href="https://www.fiilar.com" target="_blank" rel="noopener">www.fiilar.com</a> ·
        <a href="mailto:${EMAIL}">${EMAIL}</a>
      </div>
    </div>
  </footer>

  <script>
    // Many in-app browsers refuse navigator.clipboard; execCommand still copies there.
    const copy = async (text) => {
      try { await navigator.clipboard.writeText(text); return true } catch {}
      const t = Object.assign(document.createElement("textarea"), { value: text })
      document.body.append(t)
      t.select()
      const ok = document.execCommand("copy")
      t.remove()
      return ok
    }
    for (const b of document.querySelectorAll("[data-copy]")) {
      b.hidden = false
      b.addEventListener("click", async () => {
        if (!(await copy(b.dataset.copy))) return
        b.textContent = "Copied"
        setTimeout(() => (b.textContent = "Copy"), 2000)
      })
    }
  </script>

</body>
</html>
`

const shareFor = (job, url) => ({
  url,
  image: job.ogImage && `${SITE}/${job.slug}/${job.ogImage}`,
  imageAlt: job.meta.ogTitle,
})

const jobPage = (job) =>
  page({
    base: "../",
    meta: job.closes
      ? { ...job.meta, description: `${job.meta.description} Open till ${closing(job)}.`, ogDescription: `${job.meta.ogDescription} Open till ${closing(job)}.` }
      : job.meta,
    share: shareFor(job, `${SITE}/${job.slug}/`),
    headerCta: true,
    main: [
      [
        `<section class="hero">`,
        `  <span class="tag">We're hiring · ${esc(job.city)}</span>`,
        `  <h1>${esc(job.title)}</h1>`,
        `  <p class="lede">${job.lede}</p>`,
        ``,
        pad(chips(job), 2),
        ``,
        `  <a class="cta" href="#apply">Apply now →</a>`,
        `</section>`,
      ].join("\n"),
      ...job.sections.map(section),
      applyCard(job),
      ...(job.afterApply ?? []).map(section),
    ].join("\n\n"),
  })

const cities = [...new Set(jobs.map((j) => j.city))].join(" · ")
const titles = jobs.map((j) => j.title).join(", ")

const listPage = () =>
  page({
    base: "",
    meta: {
      title: `Careers at Fiilar · Open roles in ${cities}`,
      description: `Fiilar is hiring in ${cities}: ${titles}. See the roles and apply.`,
      ogTitle: "We're hiring at Fiilar",
      ogDescription: `Open roles in ${cities}: ${titles}. Apply today.`,
    },
    // The list's share preview is the first role's image: put the role you are pushing first in jobs.mjs.
    share: shareFor(jobs[0], `${SITE}/`),
    headerCta: false,
    main: [
      [
        `<section class="hero">`,
        `  <h1>Open roles</h1>`,
        `  <p class="lede">We're building the trusted marketplace for spaces in Nigeria.</p>`,
        `</section>`,
      ].join("\n"),
      [
        `<section class="block">`,
        `  <div class="roles">`,
        ...jobs.map((job) =>
          pad(
            [
              `<a class="role" href="${job.slug}/">`,
              `  <h2>${esc(job.title)}</h2>`,
              pad(chips(job), 2),
              `  <span class="more">View role →</span>`,
              `</a>`,
            ].join("\n"),
            4,
          ),
        ),
        `  </div>`,
        `</section>`,
      ].join("\n"),
    ].join("\n\n"),
  })

const pages = { "index.html": listPage() }
for (const job of jobs) pages[`${job.slug}/index.html`] = jobPage(job)

const stale = []
for (const [file, html] of Object.entries(pages)) {
  const path = join(ROOT, file)
  if (process.argv.includes("--check")) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== html) stale.push(file)
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, html)
    console.log(`wrote ${file}`)
  }
}
if (stale.length) {
  console.error(`Out of date, run node build.mjs: ${stale.join(", ")}`)
  process.exit(1)
}
